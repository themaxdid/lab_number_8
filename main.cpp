#include <iostream>
#include <iomanip>

/*
Вариант 2.
Дано целое число типа long long, выведите на экран содержимое 
каждого из его байтов, используя знания по указателям. 
Дайте обоснование полученному результату.
*/

int main() {
    long long number = 0x1122334455667788;
    unsigned char* bytePtr = reinterpret_cast<unsigned char*>(&number);
    // & у переменной - взятие адреса самой первой ячейки, с которой 
    // начинается переменная
    // bytePtr - переменная, хранящая адрес ячейки памяти размером 1 байт

    for (size_t i = 0; i < sizeof(long long); ++i) {
        std::cout << "byte " << i << ": 0x" 
                  << std::hex << std::setw(2) << std::setfill('0') 
                  // hex - перевод потока cout на 16 с.с.
                  // setw и setfill - резервация 2 "клеточек" на вывод числа
                  // если 1 ячейка пуста, то заполняется нулем
                  << static_cast<int>(bytePtr[i]) << std::endl;
                  // static_cast<int> - перевод char в число, а не букву
    }

    return 0;
}

// из-за того, что современные процессоры используют правило Little-Endian,
// то байты записываются с конца в начало.
// число = 0x12345678
// byte 1 byte 2 byte 3 byte 4
//   78     56     34     12 
// поэтому вывод происходит с 0x78